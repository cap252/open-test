"""Generate standalone experiment YAML files from shared maintainer definitions."""

import argparse
from copy import deepcopy
from dataclasses import asdict, replace
from pathlib import Path

import yaml

from opennpu_quant.configuration import (
    DEFAULT_INPUT_CACHE_BYTES,
    PRESETS,
    validate,
)
from opennpu_quant.ort.config import DEFAULT_GPU_MEMORY_LIMIT, OrtConfig
from opennpu_quant.quant.adaround_cache import ActivationCacheConfig
from opennpu_quant.quant.config import AdaroundConfig, CalibrationConfig
from opennpu_quant.quant.scheme import Scheme

DIRECTORY = (
    Path(__file__).resolve().parents[1] / "src/opennpu_quant/resources/experiments"
)
HEADER = (
    "# Generated by tools/build_presets.py. Edit its definitions, then use --write.\n"
)

CORE_PERCENTILES = {
    "resnet18": {"pot": 99.99, "float": 99.999},
    "resnet50": {"pot": 99.9, "float": 99.999},
    "mobilenet_v2": {"pot": 99.9, "float": 99.99},
    "mobilenet_v3_large": {"pot": 99.9, "float": 99.99},
    "efficientnet_b0": {"pot": 99.9, "float": 99.99},
    "inception_v3": {"pot": 99.99, "float": 99.99},
    "yolov5s": {"pot": 99.99, "float": 99.99},
    "ssd_mobilenet_v2_320": {"pot": 99.99, "float": 99.999},
    "deeplabv3_mnv2_voc": {"pot": 99.9, "float": 99.9},
    "retinaface_mnet025_640": {"pot": 99.9, "float": 99.9},
}
CORE_MODELS = tuple(CORE_PERCENTILES)
CNN30_ADDITIONS = (
    "resnet101",
    "mobilenet_v1",
    "efficientnet_lite4",
    "squeezenet1_1",
    "shufflenet_v2_x1_0",
    "vgg16",
    "yolov3_tiny",
    "yolov4_tiny",
    "yolov5n",
    "yolov7_tiny",
    "yolov8n",
    "nanodet_plus_m_320",
    "retinanet_resnet50_fpn",
    "yolox",
    "yolov7_face",
    "unet_resnet50_voc",
    "deeplabv3_r50_voc",
    "fcn_r50_voc",
    "yolov5s_seg",
    "mobilefacenet_relu_foamliu",
)


def _models():
    return dict(core10=list(CORE_MODELS), cnn30=[*CORE_MODELS, *CNN30_ADDITIONS])


def _common():
    ort, calibration, adaround = OrtConfig(), CalibrationConfig(), AdaroundConfig()
    schemes = {}
    for family in ("pot", "float", "sym_pot"):
        policy = Scheme()
        if family != "float":
            policy = replace(
                policy, activation_scale="pot_ceil", weight_scale="pot_ceil"
            )
        if family == "sym_pot":
            policy = replace(
                policy, activation_symmetric=True, weight_granularity="per_tensor"
            )
        schemes[family] = {
            k: v
            for k, v in policy.to_dict().items()
            if k not in ("histogram_bins", "quantized_bins")
        }
        schemes[family]["percentile"] = "per_model"
    conditions = {"fp32": {}}
    for family in schemes:
        conditions[family + "_rtn"] = dict(scheme=family)
        conditions[family + "_adaround"] = dict(scheme=family, adaround=True)
    return dict(
        runtime=dict(
            device="cuda:0",
            intra_op_threads=ort.intra_op_threads,
            inter_op_threads=ort.inter_op_threads,
            cuda=dict(gpu_mem_limit=DEFAULT_GPU_MEMORY_LIMIT),
        ),
        calibration=dict(
            input_cache=dict(enabled=True, max_bytes=DEFAULT_INPUT_CACHE_BYTES),
            device="run",
            histogram_bins=calibration.histogram_bins,
            samples=dict(imagenet=1000, coco=128, widerface=128, voc=128),
        ),
        schemes=schemes,
        conditions=conditions,
        percentiles={},
        # Keep the existing explicit fields. Omitted API defaults stay omitted in YAML.
        adaround={
            k: getattr(adaround, k)
            for k in (
                "steps",
                "learning_rate",
                "warmup_fraction",
                "regularization",
                "beta_start",
                "beta_end",
                "seed",
                "batch_size",
                "window_samples",
                "window_bytes",
                "window_steps",
                "device",
            )
        },
        evaluation=dict(limit=None),
        output=dict(save_qdq_models=False, save_predictions=False),
        report=dict(
            primary_metric=dict(
                classification="top1",
                detection="AP",
                face="AP_medium",
                segmentation="mIoU",
            ),
            target_mean_recovery=None,
        ),
        activation_cache=dict(enabled=True, **asdict(ActivationCacheConfig())),
    )


def presets():
    """Return complete independent configs. No runtime code imports this module."""
    models, common = _models(), _common()
    assert set(models) == set(PRESETS)
    result = {}
    for name in PRESETS:
        config = dict(name=name, models=list(models[name]), **deepcopy(common))
        samples = config["calibration"]["samples"]
        metrics = config["report"]["primary_metric"]
        if name == "core10":
            config["schemes"].pop("sym_pot")
            config["conditions"] = {
                k: v
                for k, v in config["conditions"].items()
                if not k.startswith("sym_pot")
            }
            config["percentiles"] = deepcopy(CORE_PERCENTILES)
            config["report"]["target_mean_recovery"] = 98.0
        else:
            samples["lfw_mobilefacenet"] = 128
            metrics["instance_segmentation"] = "mask_AP"
            metrics["face_verification"] = "verification_accuracy"
            config["percentiles"] = {
                model: dict.fromkeys(config["schemes"], 99.99)
                for model in config["models"]
            }
        validate(config)
        result[name] = config
    return result


def render():
    return {
        name + ".yaml": (HEADER + yaml.safe_dump(config, sort_keys=False)).encode(
            "utf-8"
        )
        for name, config in presets().items()
    }


def synchronize(directory=DIRECTORY, *, write=False):
    """Check without writing, or explicitly replace generated files. Return mismatches."""
    directory = Path(directory)
    expected = render()
    changed = []
    for name, payload in expected.items():
        path = directory / name
        if not path.is_file() or path.read_bytes() != payload:
            changed.append(name)
            if write:
                directory.mkdir(parents=True, exist_ok=True)
                path.write_bytes(payload)
    return changed


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="Check committed files without writing (default)",
    )
    mode.add_argument(
        "--write", action="store_true", help="Regenerate the two standalone YAML files"
    )
    args = parser.parse_args(argv)
    changed = synchronize(write=args.write)
    if changed:
        print(("Updated: " if args.write else "Out of date: ") + ", ".join(changed))
        if not args.write:
            print(
                "Review the definitions, then run python tools/build_presets.py --write"
            )
            return 1
    else:
        print("Both presets match their definitions.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
